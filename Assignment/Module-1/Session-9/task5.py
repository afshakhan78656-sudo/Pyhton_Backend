my_fav_apps=["Instagram", "Facebook", "YouTube", "Spotify", "Snapchat"]
print("My favorite apps are:",my_fav_apps)

#sort the list of apps in alphabetical order
my_fav_apps.sort()
print("After sorting, my favorite apps are:",my_fav_apps)

#reverse the list of apps
my_fav_apps.reverse()
print("After reversing, my favorite apps are:",my_fav_apps)

