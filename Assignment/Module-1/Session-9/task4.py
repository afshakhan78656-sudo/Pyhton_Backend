my_fav_apps=["Instagram", "WhatsApp", "YouTube", "Spotify", "Snapchat"]
print("My favorite apps are:",my_fav_apps)

my_fav_apps.remove("Snapchat")
print("After removing Snapchat, my favorite apps are:",my_fav_apps)

my_fav_apps.pop()
print("After popping the last app, my favorite apps are:",my_fav_apps)

print("Final list of my favorite apps are:",my_fav_apps)