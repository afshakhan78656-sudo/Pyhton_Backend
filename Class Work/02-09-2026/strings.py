#Methods of String in Python
s="Python Programming"
print("Original String:", s)

print("Length of String: ", len(s))
print("String in Capitalize : ", s.capitalize())
print("String in Upercase : ", s.upper())
print("String in Lowercase : ", s.lower())
print("String in Casefold : ", s.casefold())
print("String Centered : ", s.center(30, '*'))
print("String Count : ", s.count('P'))
print("String Find letters : ", s.find('y')) #index
print("String Index of letters : ", s.index('P',2))
print("String is Alphanumeric : ", s.isalnum())
print("String is Alphabetic : ", s.isalpha()) #space aa raha h na isliye false 
print("String in Swapcase : ", s.swapcase())
print("String in Title : ", s.title())
print("String in Replace : ", s.replace('P','T'))

